import {readFileSync} from 'node:fs';import assert from 'node:assert/strict';
const source=readFileSync('src/data.js','utf8');
const champions=JSON.parse(source.match(/export const champions=(\[[\s\S]*?\]);/)[1]);
const levels=JSON.parse(source.match(/export const levels=(\[[\s\S]*?\]);/)[1]);
assert.equal(champions.length,105,'Must preserve all 105 candidates');
assert.equal(levels.length,33,'Must preserve all 33 Self Aura levels');
assert.equal(new Set(champions.map(x=>x.id)).size,105,'Champion IDs must be unique');
assert.equal(new Set(levels.map(x=>x.id)).size,33,'Level IDs must be unique');
assert.deepEqual(levels.map(x=>x.id),Array.from({length:33},(_,i)=>i+1));
assert.ok(source.includes('submissions'),'Keep legacy submission archive');
const bugs=readFileSync('src/data/bugSubmissions.ts','utf8');
for(const n of ['006','007','008'])assert.ok(bugs.includes("id:'"+n+"'"),'Missing historical submission '+n);
assert.ok(bugs.includes("approvalStatus:'not_verified'"));
for(const path of ['src/pages/Home.jsx','src/pages/Champions.jsx','src/pages/Paradise.jsx','src/pages/Syafaat.jsx','src/pages/Grand.jsx','src/components/Header.jsx','src/components/Footer.jsx','src/components/Books.jsx'])assert.ok(readFileSync(path,'utf8').length>100,'Empty page '+path);
console.log('Content integrity checks PASS: 105 champions, 33 levels, 3 known numbered submissions, modular pages.');
